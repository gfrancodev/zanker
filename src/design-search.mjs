import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {PLUGIN_ROOT, readJsonFile, resolveWithin, toSafeSlug, writeJsonFile} from './common.mjs';

const VENDOR_SCRIPT = path.join(PLUGIN_ROOT, 'vendor/ui-ux-pro-max/scripts/search.py');

/** Flags allowed through the Zanker wrapper (design-system mode only). */
const ALLOWED_FLAGS = new Set([
  'design-system', 'format', 'json', 'p', 'project-name', 'variance', 'motion', 'density', 'query',
]);

/**
 * @param {Record<string, unknown>} options Parsed CLI options from bridge.
 * @returns {Record<string, string|number|boolean>}
 */
function normaliseOptions(options) {
  const out = {};
  if (options.query) out.query = String(options.query);
  if (options['design-system'] === true || options['design-system'] === 'true') out['design-system'] = true;
  if (options.format) out.format = String(options.format);
  if (options.json === true || options.json === 'true') out.json = true;
  if (options.p) out.p = String(options.p);
  if (options['project-name']) out['project-name'] = String(options['project-name']);
  if (options.variance !== undefined) out.variance = Number(options.variance);
  if (options.motion !== undefined) out.motion = Number(options.motion);
  if (options.density !== undefined) out.density = Number(options.density);
  return out;
}

/**
 * @param {Record<string, unknown>} raw
 * @returns {string[]} Rejected flag names.
 */
export function findDisallowedDesignSearchFlags(raw) {
  const rejected = [];
  for (const key of Object.keys(raw)) {
    if (key === 'project') continue;
    if (!ALLOWED_FLAGS.has(key)) rejected.push(key);
  }
  return rejected;
}

/**
 * @param {Record<string, string|number|boolean>} opts
 * @returns {string[]}
 */
function buildArgv(opts) {
  const argv = [VENDOR_SCRIPT];
  if (!opts.query) throw new Error('--query required');
  argv.push(String(opts.query));
  if (opts['design-system']) argv.push('--design-system');
  if (opts.format) argv.push('--format', String(opts.format));
  if (opts.json) argv.push('--json');
  if (opts.p) argv.push('-p', String(opts.p));
  if (opts['project-name']) argv.push('-p', String(opts['project-name']));
  if (opts.variance) argv.push('--variance', String(opts.variance));
  if (opts.motion) argv.push('--motion', String(opts.motion));
  if (opts.density) argv.push('--density', String(opts.density));
  return argv;
}

/**
 * @param {object} params
 * @param {string} params.project Absolute project path.
 * @param {Record<string, unknown>} params.options Bridge options.
 * @returns {object}
 */
export function runDesignSearch({project, options}) {
  const rejected = findDisallowedDesignSearchFlags(options);
  if (rejected.length) {
    return {ok: false, reason: 'disallowed-flags', rejected};
  }
  const opts = normaliseOptions(options);
  if (!opts['design-system']) {
    return {ok: false, reason: 'design-system-required'};
  }
  if (!fs.existsSync(VENDOR_SCRIPT)) {
    return {ok: false, reason: 'vendor-missing'};
  }
  const python = spawnSync('python3', ['--version'], {encoding: 'utf8'});
  if (python.status !== 0) {
    return {ok: false, reason: 'python3-missing'};
  }
  const run = spawnSync('python3', buildArgv(opts), {
    encoding: 'utf8',
    cwd: path.dirname(VENDOR_SCRIPT),
    maxBuffer: 8 * 1024 * 1024,
  });
  if (run.status !== 0) {
    return {ok: false, reason: 'search-failed', stderr: (run.stderr || '').slice(0, 2000)};
  }
  const stdout = run.stdout || '';
  let parsed = null;
  if (opts.json) {
    try {
      parsed = JSON.parse(stdout);
    } catch {
      return {ok: false, reason: 'invalid-json', raw: stdout.slice(0, 500)};
    }
  }
  const projectRoot = path.resolve(project);
  const slug = toSafeSlug(opts.p || opts.query);
  const briefPath = resolveWithin(projectRoot, path.join('.zanker', 'design-intelligence', `${slug}.md`));
  if (!opts.json) {
    fs.mkdirSync(path.dirname(briefPath), {recursive: true});
    fs.writeFileSync(briefPath, stdout, 'utf8');
  } else if (parsed?.design_system) {
    const lines = [
      `# Design intelligence: ${slug}`,
      '',
      'Generated by UI UX Pro Max (vendored). Catalog is rank 4; user visual references override this brief.',
      '',
      '```json',
      JSON.stringify(parsed.design_system, null, 2),
      '```',
      '',
    ];
    fs.mkdirSync(path.dirname(briefPath), {recursive: true});
    fs.writeFileSync(briefPath, lines.join('\n'), 'utf8');
  }
  return {
    ok: true,
    saved: opts.json ? briefPath : briefPath,
    json: parsed,
    text: opts.json ? undefined : stdout,
  };
}
